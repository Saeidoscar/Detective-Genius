def format_run(run, font_name='B Nazanin', size_pt=12, bold=False, italic=False, color_rgb=(0,0,0)):
    run.font.name = font_name
    run.font.size = Pt(size_pt)
    run.bold = bold
    run.italic = italic
    run.font.color.rgb = RGBColor(*color_rgb)
    # Ensure complex script font is also set
    rPr = run._r.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    rFonts.set(qn('w:cs'), font_name)
    rFonts.set(qn('w:ascii'), font_name)
    rFonts.set(qn('w:hAnsi'), font_name)

def add_persian_paragraph(doc, text="", font_name='B Nazanin', size_pt=12, bold=False, italic=False, 
                          color_rgb=(0,0,0), align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=6, line_spacing=1.15):
    p = doc.add_paragraph()
    set_rtl(p)
    p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = line_spacing
    if text:
        run = p.add_run(text)
        format_run(run, font_name=font_name, size_pt=size_pt, bold=bold, italic=italic, color_rgb=color_rgb)
    return p

def add_persian_heading(doc, text, level=1, space_before=12, space_after=6):
    size_map = {1: 15, 2: 13, 3: 12}
    p = doc.add_paragraph()
    set_rtl(p)
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.keep_with_next = True
    run = p.add_run(text)
    format_run(run, font_name='B Titr' if level==1 else 'B Nazanin', size_pt=size_map.get(level, 12), bold=True, color_rgb=(20, 40, 80))
    return p

